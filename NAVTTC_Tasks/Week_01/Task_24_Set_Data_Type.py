# Problem: Class A students like {tea, coffee, juice} and Class B
# students like {coffee, juice, milk}. Print the drinks both classes
# like.

class_a_drinks = {"tea", "coffee", "juice"}
class_b_drinks = {"coffee", "juice", "milk"}
print("Liked by both:", class_a_drinks & class_b_drinks)
